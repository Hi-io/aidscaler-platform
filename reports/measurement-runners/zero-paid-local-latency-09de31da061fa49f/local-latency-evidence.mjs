export function latencyStats(rows, key, targetMs) {
  const values=rows.map(r=>r[key]).filter(finite).filter(v=>v>=0).sort((a,b)=>a-b),missing=rows.length-values.length,
    p=q=>values.length?values[Math.max(0,Math.ceil(values.length*q)-1)]:null;
  return {samples:rows.length,observed:values.length,missing,p50Ms:p(.5),p95Ms:p(.95),maxMs:values.at(-1)??null,targetMs,
    withinTarget:missing||!finite(targetMs)?null:values.length?p(.95)<targetMs:null,
    note:'Nearest-rank empirical p95; no imputation for missing/negative/incompatible clocks and no representative-latency claim from zero samples.'};
}
export function latencyReadout(report) {
  const m=report.measurements??{},p=report.protocol??LATENCY_PLAN,
    planned=(rows,count)=>[...rows,...Array.from({length:Math.max(0,count-rows.length)},()=>({state:'planned_not_observed'}))];
  return {status:report.status,errors:report.errors??[],scope:LATENCY_PLAN,
    navigation:latencyStats(planned(m.navigation??[],p.browserSamples),'renderMs',LATENCY_PLAN.targetsMs.localNavigation),
    API:latencyStats(m.apiReads??[],'wallMs',null),
    durableCommand:latencyStats(planned(m.commands??[],p.durableSamplesPerOwner*p.organizations),'ackMs',LATENCY_PLAN.targetsMs.durableCommand),
    acknowledgedAPIReadback:latencyStats(m.commands??[],'readbackMs',null),
    visibleAcknowledgedState:latencyStats(planned(m.visibleAcknowledgedState??[],p.browserFieldSamples),'visibleMs',LATENCY_PLAN.targetsMs.visibleAcknowledgedState),
    receivedFeedToDurableLocal:latencyStats(m.ingestion??[],'durableMs',LATENCY_PLAN.targetsMs.receivedFeedToDurableLocal),
    unreadOrUncommittedVersions:(m.ingestion??[]).filter(r=>!finite(r.durableMs)||r.durableMs<0),
    pageReads:report.sourceFeedPageReads??null,actualUniqueReceivedVersions:report.actualUniqueReceivedVersions??null,
    sourceClockPollDelays:(m.ingestion??[]).map(r=>({org:r.org,id:r.id,version:r.version,pollDelayMs:r.pollDelayMs??null})),
    ownerCounts:report.ownerCounts??null,expectedAccessiblePublicVersions:report.expectedAccessiblePublicVersions??null,
    sourcePublications:report.scorerOnlySourcePublications??null,invariants:report.invariants??null,
    queuedJobs:report.queuedJobs??null,providerUsage:report.usage??null,providerCalls:Array.isArray(report.usage)?report.usage.length:null,
    finalBuilds:report.finalBuilds??null,semanticPrecisionRecall:null,hardware:report.hardware??null,
    throughputRealTimeClaim:false,GenAIAttribution:false};
}
